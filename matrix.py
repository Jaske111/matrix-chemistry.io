def reduce_22(number: int) -> int:
    """Складывает цифры до диапазона 1–22."""
    while number > 22:
        number = sum(int(ch) for ch in str(number))
    return number if number > 0 else 22

def energy(number: int) -> dict:
    title, theme, light, shadow = ARCANAS[number - 1]
    return {
        "number": number,
        "title": title,
        "theme": theme,
        "light": light,
        "shadow": shadow,
    }

def calculate_matrix(name, born):
    a = reduce_22(born.day)
    b = reduce_22(born.month)
    c = reduce_22(sum(int(ch) for ch in str(born.year)))
    d = reduce_22(a + b)
    e = reduce_22(b + c)
    f = reduce_22(c + d)
    g = reduce_22(d + a)
    h = reduce_22(a + b + c)
    center = reduce_22(d + e + g)

    labels = [
        ("Личность", a), ("Таланты", b), ("Родовая энергия", c),
        ("Реализация", d), ("Земной путь", e), ("Отношения", f),
        ("Внутренний ресурс", g), ("Предназначение", h),
        ("Центр матрицы", center),
    ]
    details = [{"label": label, **energy(num)} for label, num in labels]
    return {
        "name": name,
        "birthdate": born.strftime("%d.%m.%Y"),
        "positions": details,
        "all_arcanas": [energy(i) for i in range(1, 23)],
        "center": energy(center),
    }
